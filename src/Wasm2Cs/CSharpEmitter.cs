using System.Globalization;
using System.Text;
namespace Wasm2Cs;
internal static class CSharpEmitter
{
    public static string Emit(Module module, string className)
    {
        var source = new StringBuilder("// <auto-generated/>\n#pragma warning disable CS0219 // WASM may discard locals and stack values.\nnamespace Wasm2Cs.Generated\n{\n");
        source.Append("public sealed class @").Append(className).Append("\n{\n");
        foreach (var export in module.Exports)
        {
            var function = module.Bodies[export.Value];
            source.Append("    public ").Append(function.Signature.Results == 0 ? "void" : "int")
                .Append(" @").Append(export.Key).Append('(');
            source.Append(string.Join(", ", Enumerable.Range(0, function.Signature.Parameters).Select(i => $"int v{i}")));
            source.Append(")\n    {\n").Append(EmitBody(function)).Append("    }\n");
        }
        return source.Append("}\n}\n").ToString();
    }
    private static string EmitBody(Function function)
    {
        var code = new StringBuilder();
        for (int i = function.Signature.Parameters; i < function.Locals; i++) code.Append($"        int v{i} = 0;\n");
        var stack = new Stack<string>();
        int temporary = 0;
        bool returned = false;
        void Push(string expression)
        {
            string name = $"s{temporary++}";
            code.Append($"        int {name} = {expression};\n");
            stack.Push(name);
        }
        foreach (var instruction in function.Instructions)
        {
            switch (instruction.Opcode)
            {
                case 0x0b:
                    if (!returned) code.Append(function.Signature.Results == 0 ? "        return;\n" : $"        return {stack.Pop()};\n");
                    break;
                case 0x0f:
                    code.Append(function.Signature.Results == 0 ? "        return;\n" : $"        return {stack.Pop()};\n");
                    returned = true;
                    break;
                case 0x1a: stack.Pop(); break;
                case 0x20: Push($"v{instruction.Operand}"); break;
                case 0x21: case 0x22:
                    string value = stack.Pop();
                    code.Append($"        v{instruction.Operand} = {value};\n");
                    if (instruction.Opcode == 0x22) stack.Push(value);
                    break;
                case 0x41: Push(instruction.Operand.ToString(CultureInfo.InvariantCulture)); break;
                case 0x6a: case 0x6b: case 0x6c:
                    string right = stack.Pop(), left = stack.Pop();
                    string operation = instruction.Opcode == 0x6a ? "+" : instruction.Opcode == 0x6b ? "-" : "*";
                    Push($"unchecked({left} {operation} {right})");
                    break;
            }
        }
        return code.ToString();
    }
}
